/** الافتراضي ملي FOUNDER_EMAILS ماشي محطوط — صاحب المنصة */
const DEFAULT_FOUNDER_EMAILS = "mobanunir@gmail.com";

export const founderEmails = (): Set<string> =>
  new Set(
    (process.env.FOUNDER_EMAILS ?? DEFAULT_FOUNDER_EMAILS)
      .split(",")
      .map((e) => e.trim().toLowerCase())
      .filter(Boolean),
  );

/**
 * واش هاد الإيميل ديال المؤسس؟
 *
 * خاصها تتنادى من الخادم بإيميل الجلسة — ماشي بشي قيمة جايّة من
 * جسم الطلب. الواجهة كتقرا `user.founder` اللي كيتحسب هنا.
 */
export const isFounder = (email: string | null | undefined): boolean =>
  Boolean(email) && founderEmails().has(String(email).trim().toLowerCase());

