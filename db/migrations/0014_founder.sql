-- ============================================================
-- شارة المؤسس
--
-- عمود واحد للعرض السريع: بطاقات البحث كتجيب البائع بـJOIN، فبلا
-- هاد العمود كل بطاقة كتحتاج استعلام زايد باش تعرف واش صاحبها
-- هو المؤسس.
--
-- المرجع ديال الامتياز ماشي هاد العمود — هو متغيّر البيئة
-- FOUNDER_EMAILS (نفس فلسفة ADMIN_EMAILS): حتى إلا شي واحد
-- بدّل هاد العمود بـUPDATE، ماكيربح غير الشارة فالعرض، وماكيربحش
-- الترويج المجاني ولا النشر بلا حدود — هادوك كيتقرّرو فالخادم من
-- إيميل الجلسة وقت الطلب. والعمود كيتزامن مع متغيّر البيئة ملي
-- كيدخل صاحبو، فأي تبديل يدوي كيترجع وحدو.
-- ============================================================

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS founder boolean NOT NULL DEFAULT false;

-- صاحب المنصة. إلا بدّلتي FOUNDER_EMAILS، بدّل الإيميل هنا حتى هو
-- (ولا خليه — العمود كيتزامن وحدو عند أول دخول).
UPDATE users SET founder = true WHERE lower(email) = 'mobanunir@gmail.com';
