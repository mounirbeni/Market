-- ============================================================
--  مراجع الإعلانات الجديدة
--
--  الإعلانات المرفقة عندها مراجع c001…c069 و m001…m035.
--  الإعلانات اللي كينشرو المستخدمين خاصها مرجع فريد بلا تصادم،
--  ولا سباق بين طلبين فنفس اللحظة — علاش تسلسل ديال Postgres.
-- ============================================================

CREATE SEQUENCE IF NOT EXISTS listing_ref_seq START 1000;

-- كنضمنو أنّ التسلسل ديما فوق أكبر مرجع موجود
SELECT setval(
  'listing_ref_seq',
  GREATEST(
    1000,
    COALESCE(
      (SELECT max(substring(ref from '[0-9]+')::bigint) FROM listings
       WHERE ref ~ '^[cm][0-9]+$'),
      0
    ) + 1
  ),
  false
);
