-- 0016 — صورة شخصية مع طلب التوثيق.
--
-- المشرف كان كيشوف الوثيقة والاسم المكتوب فالحساب، وصافي. ماكانش
-- عندو كيفاش يقارن وجه صاحب الحساب مع الصورة اللي فالبطاقة — يعني
-- شي واحد يقدر يرفع بطاقة ماشي ديالو وتعدي.
--
-- دابا الطلب فيه صورة شخصية والبطاقة فاليد. كتّخزن تحت private/
-- بحال الوثيقة، وماكتبانش لا فالإعلانات لا فالبروفايل — غير
-- لمراجعة الطلب.
--
-- nullable: الطلبات القديمة (قبل هاد الهجرة) ماعندهاش صورة، والمشرف
-- خاصو يقدر يكمّل مراجعتها. الإلزام كاين فالواجهة والخادم للطلبات
-- الجداد فقط.
ALTER TABLE verifications ADD COLUMN IF NOT EXISTS selfie_path text;

COMMENT ON COLUMN verifications.selfie_path IS
  'صورة شخصية بالوثيقة فاليد — مسار private/، للمراجعة فقط';
