-- ============================================================
-- استكمال الملف الشخصي — إلزامي قبل النشر
--
-- التسجيل بالإيميل وحدو ماكيطلبش لا رقم لا مدينة لا اسم حقيقي —
-- الاسم كيتولّد افتراضياً ("مستعمل طريق"). عمود واحد (onboarded)
-- كيقول واش المستخدم دار الخطوة الإلزامية ولا لا، بلا ما نخمّنو
-- من قيم الحقول وحدها (النوع مثلاً عندو قيمة افتراضية صحيحة —
-- "particulier" — فماكاينش قيمة "خاوية" نميّزو بيها).
--
-- الحسابات القديمة اللي عندها أصلاً اسم حقيقي، رقم، ومدينة —
-- ماخصهاش تتوقف: كنعتبروها "دارت الخطوة" من واقع البيانات
-- ديالها، ماشي تخمين.
-- ============================================================

ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarded boolean NOT NULL DEFAULT false;

UPDATE users SET onboarded = true
WHERE phone IS NOT NULL
  AND city IS NOT NULL
  AND name IS NOT NULL AND length(trim(name)) >= 2 AND name <> 'مستعمل طريق'
  AND onboarded = false;
